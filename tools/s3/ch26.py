def info(i):
    return PUZ[str(i)]


def ans(i):
    return f"答案（由左到右）：{info(i)['answer']}。"


def lies(i):
    return "、".join(f"線索 {x}" for x in info(i)["lies"]) + "是假的。" if info(i)["lies"] else ""


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, note=None, drinks=False):
    d = dict(id=i, title=title, task="把大家排好。" if not drinks else "排好隊，也填好每一顆買的飲料。",
             hints=[h1, h2, lies(i) + ans(i)], enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen, solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + "線索：" + "　".join(info(i)["clues"]) + " " + lies(i) + ans(i)
    return d


