def info(i):
    return PUZ[str(i)]


def answer(i):
    p = info(i)
    e = p["engine"]
    if e == "mines":
        return f"第一步：{p['first']} {'一定安全' if p['first_safe'] else '一定是雷'}。" + (f"{'、'.join(p['lies'])} 說的是謊話。" if p["lies"] else "")
    if e == "captcha":
        out = []
        for n, r in enumerate(p["rounds"], 1):
            lie = ("（" + "、".join(f"第 {x} 句" for x in r["lies"]) + "是謊話）") if r["lies"] else ""
            out.append(f"第 {n} 題選 {'、'.join(map(str, r['answer']))}{lie}")
        return "答案：" + "；".join(out) + "。"
    if e == "liars":
        nar = "我那句是謊話。" if p.get("narrator") and not p["narrator"][1] else ""
        return nar + f"答案：{p['answer']}。"
    if e == "rules":
        lie = ("、".join(f"第 {x} {'張' if p['kind'] == 'zendo' else '行'}" for x in p["lies"]) + "是謊話。") if p["lies"] else ""
        if p["kind"] == "zendo":
            return lie + f"規則是「{p['secret']}」，符合的是 {'、'.join('ABCDEF'[x - 1] for x in p['answer'])}。"
        return lie + f"密碼是{p['secret']}。"
    if e == "wires":
        return ("、".join(p["lies"]) + "是假的。" if p["lies"] else "") + f"打開 {'、'.join(p['answer'])}。"
    if e == "order":
        return ("、".join(f"線索 {x}" for x in p["lies"]) + "是假的。" if p["lies"] else "") + f"答案（由左到右）：{p['answer']}。"
    if e == "maze":
        return ("、".join(p["lies"]) + " 的箭頭是謊話。" if p["lies"] else "") + "路線：" + " → ".join(p["path"]) + "。"
    if e == "pins":
        return ("、".join(f"規則 {x}" for x in p["lies"]) + "是假的。" if p["lies"] else "") + f"密碼是 {p['answer']}。"
    if e == "mirrors":
        ans = "、".join(f"{k} {v.replace(chr(92), '＼').replace('/', '／')}" for k, v in p["answer"].items())
        return ("、".join(p["lies"]) + " 的鏡子是謊話。" if p["lies"] else "") + f"答案：{ans}。"
    raise ValueError(e)


