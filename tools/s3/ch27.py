def info(i):
    return PUZ[str(i)]


def route(i, k=None):
    p = info(i)["path"]
    return " → ".join(p if k is None else p[: k + 1])


def lies(i):
    return "、".join(info(i)["lies"]) + " 的箭頭是謊話。" if info(i)["lies"] else ""


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, note=None):
    d = dict(id=i, title=title, task=f"走到我這裡。最多 {info(i)['steps']} 步。", hints=[h1, h2, lies(i) + "路線：" + route(i) + "。"],
             enter=enter, first=first_m, clear=clear, doc=dict(screen=screen, solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + lies(i) + "路線：" + route(i) + f"。從起點走得到 {info(i)['reach']} 格。"
    return d


