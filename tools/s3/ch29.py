def info(i):
    return PUZ[str(i)]


def ans(i):
    return "答案：" + "、".join(f"{k} {v.replace(chr(92), '＼').replace('/', '／')}" for k, v in info(i)["answer"].items()) + "。"


def lies(i):
    return "、".join(info(i)["lies"]) + " 的鏡子是謊話。" if info(i)["lies"] else ""


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, note=None):
    d = dict(id=i, title=title, task="讓雷射打到我。", hints=[h1, h2, lies(i) + ans(i)], enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen, solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + lies(i) + ans(i) + f"光線轉 {info(i)['turns']} 次彎。"
    return d


