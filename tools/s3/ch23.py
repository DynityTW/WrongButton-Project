def info(i):
    return PUZ[str(i)]


def ans(i):
    return f"答案：{info(i)['answer']}。"


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, h3=None, note=None, task=None):
    p = info(i)
    goal_task = task or "找出說謊的按鈕。"
    d = dict(id=i, title=title, task=goal_task, hints=[h1, h2, h3 or ans(i)], enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen, solution=solution, clue=clue))
    nar = f"；The Button：{p['narrator'][0]}（{'真話' if p['narrator'][1] else '謊話'}）" if p["narrator"] else ""
    d["doc"]["note"] = (note + " " if note else "") + "題目：" + "　".join(p["stmts"]) + nar + f"。身分：{p['roles']}。"
    return d


