def info(i):
    return PUZ[str(i)]


def ans(i):
    return f"打開 {'、'.join(info(i)['answer'])}。"


def lies(i):
    return "、".join(info(i)["lies"]) + "是假的。" if info(i)["lies"] else ""


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, note=None):
    d = dict(id=i, title=title, task="讓目標的燈亮起來，其他燈都暗。", hints=[h1, h2, lies(i) + ans(i)], enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen, solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + lies(i) + ans(i)
    return d


