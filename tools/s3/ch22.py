def answers(i):
    rs = PUZ[str(i)]
    parts = []
    for n, r in enumerate(rs, 1):
        a = "、".join(map(str, r["answer"]))
        parts.append(f"第 {n} 題選 {a}" if len(rs) > 1 else f"選 {a}")
    return "答案：" + "；".join(parts) + "。"


def lies(i):
    rs = PUZ[str(i)]
    parts = []
    for n, r in enumerate(rs, 1):
        if r["lies"]:
            ls = "、".join(f"第 {x} 句" for x in r["lies"])
            parts.append(f"第 {n} 題的{ls}" if len(rs) > 1 else ls)
    return "、".join(parts)


def first_pick(i):
    r = PUZ[str(i)][0]
    return f"第 1 題的答案有 {len(r['answer'])} 格，包括第 {r['answer'][0]} 格。"


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, h3=None, note=None):
    hints = [h1, h2, h3 or answers(i)]
    n = len(PUZ[str(i)])
    d = dict(id=i, title=title, task="通過「我不是機器人」驗證，再按我。", hints=hints, enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen + f"（{n} 題）", solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + "題目：" + " ／ ".join(" ".join(r["stmts"]) + f" → {r['answer']}" for r in PUZ[str(i)])
    return d


