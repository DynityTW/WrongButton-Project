def info(i):
    return PUZ[str(i)]


def ans(i):
    return f"密碼是 {info(i)['answer']}。"


def lies(i):
    return "、".join(f"規則 {x}" for x in info(i)["lies"]) + "是假的。" if info(i)["lies"] else ""


def L(i, title, h1, h2, enter, first_m, clear, screen, solution, clue, note=None):
    d = dict(id=i, title=title, task="設定符合所有規則的密碼。", hints=[h1, h2, lies(i) + ans(i)], enter=enter, first=first_m, clear=clear,
             doc=dict(screen=screen, solution=solution, clue=clue))
    d["doc"]["note"] = (note + " " if note else "") + "規則：" + "　".join(info(i)["rules"]) + " " + lies(i) + ans(i)
    return d


